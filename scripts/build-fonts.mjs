// scripts/build-fonts.mjs — the site's fonts, cut down to the characters the site uses.
//
// Barlow (text) and Barlow Condensed (headings) come from the @fontsource packages as two files per
// face: "latin" and "latin-ext" (Uzbek needs ş and ğ from the second). Each file carries every
// glyph of its part; the site uses a fraction of them. This script collects every character that
// appears in the pages, the theme and the simulations, and writes copies of the font files that
// hold only those characters, plus fonts.css with one @font-face rule per file.
//
//   node scripts/build-fonts.mjs      (also run by `npm run dev` and `npm run build`)
//
// Output: docs/.vitepress/theme/fonts/ (generated, not in git). A character that Barlow does not
// have at all (Greek letters, subscripts) is listed at the end; the browser shows it in the next
// font of the stack, exactly as before.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs/.vitepress/theme/fonts');
const FACES = [
  { pkg: '@fontsource/barlow', family: 'Barlow', base: 'barlow', weight: 400, style: 'normal' },
  { pkg: '@fontsource/barlow', family: 'Barlow', base: 'barlow', weight: 400, style: 'italic' },
  { pkg: '@fontsource/barlow', family: 'Barlow', base: 'barlow', weight: 500, style: 'normal' },
  { pkg: '@fontsource/barlow', family: 'Barlow', base: 'barlow', weight: 700, style: 'normal' },
  { pkg: '@fontsource/barlow-condensed', family: 'Barlow Condensed', base: 'barlow-condensed', weight: 400, style: 'normal' },
  { pkg: '@fontsource/barlow-condensed', family: 'Barlow Condensed', base: 'barlow-condensed', weight: 600, style: 'normal' },
];
const PARTS = ['latin', 'latin-ext'];
// Text is read from these places. Notes under docs/superpowers are not pages of the site.
const SOURCES = [
  { dir: 'docs', test: /\.(md|vue|js|mjs|css|json)$/, skip: /(^|\/)(superpowers|public|cache|fonts)(\/|$)/ },
  { dir: 'src', test: /\.js$/, skip: /^$/ },
];
// Always kept, whether or not a page uses them yet: printable ASCII and common punctuation.
const ALWAYS = Array.from({ length: 0x7f - 0x20 }, (_, i) => String.fromCodePoint(0x20 + i)).join('') + '’‘“”–—…·×°±≈≤≥−';

function walk(dir, test, skip, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (skip.test(path.relative(ROOT, file))) continue;
    if (entry.isDirectory()) walk(file, test, skip, out);
    else if (test.test(entry.name)) out.push(file);
  }
  return out;
}

const files = SOURCES.flatMap((s) => walk(path.join(ROOT, s.dir), s.test, s.skip));
const sourceOf = (face, part) => path.join(ROOT, 'node_modules', face.pkg, 'files', `${face.base}-${part}-${face.weight}-${face.style}.woff2`);
const nameOf = (face, part) => `${face.base}-${part}-${face.weight}-${face.style}.woff2`;
const cssFile = path.join(OUT, 'fonts.css');

// Nothing to do when the output is newer than everything it is made from.
const newest = Math.max(fs.statSync(fileURLToPath(import.meta.url)).mtimeMs, fs.statSync(path.join(ROOT, 'package-lock.json')).mtimeMs, ...files.map((f) => fs.statSync(f).mtimeMs));
const outputs = [cssFile, ...FACES.flatMap((f) => PARTS.map((p) => path.join(OUT, nameOf(f, p))))];
if (!process.argv.includes('--force') && outputs.every((f) => fs.existsSync(f) && fs.statSync(f).mtimeMs >= newest)) {
  console.log('fonts: up to date');
  process.exit(0);
}

const used = new Set(ALWAYS);
for (const file of files) for (const ch of fs.readFileSync(file, 'utf8')) if (ch >= ' ') used.add(ch);
const text = [...used].join('');

/** The unicode-range the package declares for one part of one face (the browser uses it to pick a file). */
function rangeOf(face, part) {
  const css = fs.readFileSync(path.join(ROOT, 'node_modules', face.pkg, `${face.weight}${face.style === 'italic' ? '-italic' : ''}.css`), 'utf8');
  const rule = css.split('@font-face').find((r) => r.includes(`${face.base}-${part}-${face.weight}-${face.style}.woff2`));
  const range = rule && rule.match(/unicode-range:\s*([^;]+);/);
  if (!range) throw new Error(`no unicode-range for ${nameOf(face, part)} in ${face.pkg}`);
  return range[1].trim();
}
const inRange = (range, cp) => range.split(',').some((r) => {
  const m = r.trim().match(/^U\+([0-9A-F]+)(?:-([0-9A-F]+))?$/i);
  return m && cp >= parseInt(m[1], 16) && cp <= parseInt(m[2] || m[1], 16);
});

fs.mkdirSync(OUT, { recursive: true });
let before = 0, after = 0, css = `/* Generated by scripts/build-fonts.mjs from ${[...new Set(FACES.map((f) => f.pkg))].join(' and ')}; do not edit.\n   Barlow and Barlow Condensed, cut down to the characters the site uses. SIL Open Font License 1.1. */\n`;
const ranges = {};
for (const face of FACES) {
  for (const part of PARTS) {
    const source = fs.readFileSync(sourceOf(face, part));
    const subset = await subsetFont(source, text, { targetFormat: 'woff2' });
    fs.writeFileSync(path.join(OUT, nameOf(face, part)), subset);
    before += source.length; after += subset.length;
    const range = rangeOf(face, part);
    (ranges[face.family] ||= []).push(range);
    css += `@font-face {\n  font-family: '${face.family}';\n  font-style: ${face.style};\n  font-weight: ${face.weight};\n  font-display: swap;\n  src: url(./${nameOf(face, part)}) format('woff2');\n  unicode-range: ${range};\n}\n`;
  }
}
fs.writeFileSync(cssFile, css);

// Characters the site uses that neither part of a family covers: they show in a fallback font.
const outside = [...used].filter((ch) => !Object.values(ranges)[0].some((r) => inRange(r, ch.codePointAt(0)))).sort();
const kb = (n) => `${(n / 1000).toFixed(1)} KB`;
console.log(`fonts: ${FACES.length * PARTS.length} files, ${kb(before)} -> ${kb(after)} (${used.size} characters from ${files.length} source files)`);
if (outside.length) console.log(`fonts: ${outside.length} characters are outside Barlow's latin and latin-ext parts and use a fallback font: ${outside.join(' ')}`);
